-- Group tables created inside EACH tenant schema (search_path is set to the tenant schema before this runs).
-- The member table is owned by tenant-service (its Flyway migration db/migration/tenant/V1__create_member_table.sql);
-- this script only adds the tables this service owns. Idempotent: safe to run on every startup / first request.
-- Audit columns follow tenant-service's member table (created_at / created_by / updated_at / updated_by / version).

CREATE TABLE IF NOT EXISTS member_group (
  group_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_number      VARCHAR(50)  NOT NULL UNIQUE,
  group_name        VARCHAR(150) NOT NULL,
  group_desc        VARCHAR(500),
  status            VARCHAR(30)  NOT NULL DEFAULT 'ACTIVE',
  effective_date    DATE,
  termination_date  DATE,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  created_by        VARCHAR(100),
  updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_by        VARCHAR(100),
  version           BIGINT       NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS group_membership (
  membership_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id          BIGINT       NOT NULL REFERENCES member_group (group_id),
  member_id         BIGINT       NOT NULL REFERENCES member (member_id),
  start_date        DATE         NOT NULL,
  end_date          DATE,
  created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  created_by        VARCHAR(100),
  updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_by        VARCHAR(100),
  version           BIGINT       NOT NULL DEFAULT 0
);

-- A member can have only one open (end_date IS NULL) membership in a given group
CREATE UNIQUE INDEX IF NOT EXISTS ux_group_membership_open
  ON group_membership (group_id, member_id) WHERE end_date IS NULL;
CREATE INDEX IF NOT EXISTS ix_group_membership_member ON group_membership (member_id);
